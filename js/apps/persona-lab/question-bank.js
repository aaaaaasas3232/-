/**
 * 人设机 · 题库
 *
 * 「让用户通过提问观察这个人设满不满意」是本 App 的主线,题库是它的脚手架 ——
 * 用户想不出问什么的时候,照着问一轮就知道这张卡哪里空。
 *
 * ── 相对原型的调整 ────────────────────────────────────────────────
 *
 * 1. **MBTI 从 60 题砍到 16 题。** 原型自己的进度条占位写的就是 `1/16`
 *    (`<span id="question-counter">1/16</span>`),60 题是后来堆上去的,
 *    而且后 44 题大量重复前面的维度。在手机上一屏一题,60 题没人做得完。
 * 2. **递归题("对象二选一" / "决战动物塑之巅")的规则写清楚了。** 原型
 *    `options` 里只有第一对,后面注释写着「这里会动态生成递归选项」,
 *    而生成逻辑依赖一个从未被正确初始化的 `recursiveState`。
 *    现在明确成**擂台赛**:上一轮选中的留下,和池子里的下一个继续比。
 */

