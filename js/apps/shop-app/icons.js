/**
 * 取一个图标的 SVG 字符串。
 *
 * ★ 名字不存在时 `console.warn` 一次再回落 —— 纯视觉的静默 bug
 *   （图标名写错回落成占位）断言抓不到，只能靠一条能搜到的信号。
 */
const _warned = new Set();

export function icon(name, opts = {}) {
    const path = PATHS[name];
    if (!path) {
        if (!_warned.has(name)) {
            _warned.add(name);
            console.warn(`[shop] 图标 "${name}" 不存在，已回落成占位`);
        }
        return wrap(`<circle cx="12" cy="12" r="8.5"/><path d="M12 8v5"/><path d="M12 16h.01"/>`, opts);
    }
    return wrap(path, opts);
}

