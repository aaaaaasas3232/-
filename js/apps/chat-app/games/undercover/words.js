/** 抽一对。`mixed` 从全部里抽。 */
export function pickWordPair(type = 'mixed') {
    const pool = type === 'mixed'
        ? Object.values(BANK).flat()
        : (BANK[type] || BANK.daily);
    const pair = pool[Math.floor(Math.random() * pool.length)];
    // 随机决定哪个是卧底词 —— 固定的话玩多了会有人记住「第二个总是卧底」
    const flip = Math.random() < 0.5;
    return {
        civilian: flip ? pair[1] : pair[0],
        undercover: flip ? pair[0] : pair[1],
        source: 'bank',
    };
}

export function wordTypeLabel(key) {
    return (WORD_TYPES.find((t) => t.key === key) || WORD_TYPES[0]).label;
}

export function bankSize() {
    return Object.values(BANK).reduce((n, list) => n + list.length, 0);
}
