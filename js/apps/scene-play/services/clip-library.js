/**
 * 情景剧场 · 内置文案库(**要加文案就改这个文件**)
 *
 * ══════════════════════════════════════════════════════════════════
 *  怎么加一条文案
 * ══════════════════════════════════════════════════════════════════
 *
 * 1. 复制下面这段模板,粘到 `BUILTIN_CLIPS` 数组里(放哪一组随意,
 *    同一个 tag 的挨着放好找):
 *
 *        {
 *            id: 'clip-你的英文短名', title: '标题', tag: '日常', builtin: true,
 *            content: '第一句。第二句。第三句。',
 *        },
 *
 * 2. 把最下面的 `BUILTIN_CLIPS_VERSION` **加一**。
 *    ★ 不加的话老用户永远收不到你新写的这几条 —— 补种是按版本号触发的,
 *      版本号没变就等于「这一版没有新东西」,整段补种会被跳过。
 *
 * 3. 存盘。没有第三步,不用改别的文件。
 *
 * ── 字段表 ────────────────────────────────────────────────────────
 *
 *   | 字段      | 必填 | 说明 |
 *   |-----------|------|------|
 *   | `id`      | 必填 | 全局唯一,`clip-` 开头 + 小写英文短名,发布后**不要改** |
 *   | `title`   | 必填 | 列表上显示的名字,24 字以内(超了会被截断) |
 *   | `content` | 必填 | 正文,2~4 句 |
 *   | `tag`     | 选填 | 分类标签,12 字以内。不填就归到「全部」里,不进标签栏 |
 *   | `builtin` | 选填 | 内置的一律写 `true`。写了才认得出是「系统给的」,
 *   |           |      | 用户删掉它时才会记进墓碑、以后不再自己长回来 |
 *
 *   除这五个字段外不要再加别的键 —— `normalizeClip()` 会把不认识的键丢掉,
 *   写了也存不进去(不报错,所以很难发现)。
 *
 * ── id 怎么起 ─────────────────────────────────────────────────────
 *
 *   `clip-` + 小写英文 + 连字符。`clip-rain` / `clip-library-seat`。
 *   不要用中文、不要用数字序号(`clip-1` 这种以后插一条就全乱了)。
 *   **改 id 等于删旧的加新的**:老用户那边旧的还在,新的又会补种进来,
 *   于是同一条文案出现两遍。要改文字就只改 `title` / `content`。
 *
 * ── tag 怎么起 ────────────────────────────────────────────────────
 *
 *   两个字为主,复用下面 `BUILTIN_CLIP_TAGS` 里已有的那几个。
 *   标签栏是按「库里实际出现过的 tag」现算的,新起一个 tag 就会多一个筛选钮 ——
 *   一条文案单开一个标签没有意义,那一栏点进去永远只有一条。
 *
 * ── 正文的语气 ────────────────────────────────────────────────────
 *
 *   文案库不是范例展示,是**真的能直接用**的开头 ——
 *   用户第一次进来面对一个空输入框,最缺的就是「写点什么」。
 *
 *   - 第一人称「我」,写当下正在发生的一小段,不写前因后果
 *   - 2~4 句,句子短,给具体的东西:天气、声音、手里拿着什么
 *   - 停在一个**还没发生的地方**,把接下来交给 AI
 *   - 不写「接下来会怎样呢」这类招呼读者的话,也不写任何 emoji
 *   - 不写死角色的名字和性别 —— 谁来演由用户在情景里选
 *
 * ── 老用户怎么收到新加的文案(补种规则) ──────────────────────────
 *
 *   每次打开 App,`db.js` 的 `syncBuiltinClips()` 拿这个文件和用户库对一遍:
 *
 *     加   库里没有这个 id → 追加到末尾
 *     跳过 库里已经有这个 id → 一个字都不动(用户可能改过它)
 *     不复活 用户删过的内置 id(记在 `library.removedBuiltinClipIds`)→ 永远不再加
 *
 *   所以:改 `content` 只对新用户生效,老用户那条保持他自己看到的样子。
 *   想让所有人都拿到改后的版本,只能换一个新 id 再发一条。
 */

