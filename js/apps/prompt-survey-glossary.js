/**
 * 根据 id 找分类
 */
export function findGlossaryGroup(id) {
    return GLOSSARY_GROUPS.find(g => g.id === id) || null;
}

/**
 * 在分类里找术语
 */
export function findGlossaryTerm(groupId, word) {
    const g = findGlossaryGroup(groupId);
    if (!g) return null;
    return g.terms.find(t => t.word === word) || null;
}
